"""Offline/invisible tests for the raw app-owned login WebView2 control.

The native smoke maps the official hostname to a temporary local HTML fixture.
No request is made to the website, no login occurs, and no THS window is used.
"""

from __future__ import annotations

import json
import os
from pathlib import Path
import queue
import shutil
import tempfile
import time
import uuid

from desktop_webview import (DesktopSourceBinding, LOGIN_URL, MAX_MESSAGE_BYTES, PayloadGate,
                             SOURCE_URL, create_source_control, is_document_url, is_source_url,
                             not_ready_payload, _load_dotnet, NATIVE_TICK_INTERVAL_MS, NATIVE_TICK_EVENT)


def pure_checks() -> dict:
    assert is_document_url(SOURCE_URL) and is_document_url(LOGIN_URL)
    assert is_source_url(SOURCE_URL) and not is_source_url(LOGIN_URL)
    for value in (
        SOURCE_URL + "&teacherId=other", SOURCE_URL.replace("teacherId=", "teacherId=other&teacherId="),
        SOURCE_URL.replace("tougu.zx093.cn", "tougu.zx093.cn.evil.invalid"),
        SOURCE_URL.replace("https://", "https://tougu.zx093.cn@"),
        SOURCE_URL.replace("https:", "http:"), SOURCE_URL.replace("index.html", "index.html/"),
        SOURCE_URL + "&private=true", SOURCE_URL.replace("id=&", "id=one&id=two&"),
    ):
        assert not is_source_url(value)
    gate = PayloadGate()
    assert gate.parse(json.dumps(not_ready_payload()))["source_ready"] is False
    for raw in (
        "{", "[]", "null", "{" + '"source_ready":false,"source_ready":true' + "}",
        "{" + '"source_ready":NaN' + "}", "x" * (MAX_MESSAGE_BYTES + 1),
        "\ud800", "[" * 2000 + "]" * 2000,
    ):
        try:
            gate.parse(raw)
        except (ValueError, RecursionError):
            pass
        else:
            raise AssertionError("Malformed/oversized message accepted")
    return {"ok": True, "exact_url_gate": True, "bounded_strict_json": True}


def native_smoke() -> dict:
    if os.name != "nt":
        raise RuntimeError("Windows only")
    _load_dotnet()
    from System.Threading import Thread, ThreadStart, ApartmentState
    from System.Windows.Forms import Application, Form, Panel, DockStyle
    from System.Diagnostics import Process
    from System import Array, Byte
    from System.IO import MemoryStream
    from Microsoft.Web.WebView2.Core import CoreWebView2HostResourceAccessKind, CoreWebView2WebResourceContext

    temporary_root = (Path(tempfile.gettempdir()) / ("codex-teacher-webview-offline-" + uuid.uuid4().hex)).resolve()
    temporary_root.mkdir()
    fixture_root = temporary_root / "fixture"
    html = fixture_root / "touguapp" / "webChatRoom" / "index.html"
    html.parent.mkdir(parents=True)
    html.write_text("""<!doctype html><html><head><meta charset='utf-8'>
<meta http-equiv='Content-Security-Policy' content="default-src 'none'; script-src 'unsafe-inline'; connect-src 'none'; img-src 'none'; frame-src 'none'">
<title>Offline owned WebView2 fixture</title></head><body>Offline fixture only</body></html>""", encoding="utf-8")
    output: queue.Queue = queue.Queue()

    def worker() -> None:
        form, binding, browser_pid = None, None, None
        try:
            payloads, statuses = [], []
            thread_id = int(Thread.CurrentThread.ManagedThreadId)

            def payload(value):
                assert int(Thread.CurrentThread.ManagedThreadId) == thread_id
                payloads.append(value)

            def status(value):
                assert int(Thread.CurrentThread.ManagedThreadId) == thread_id
                statuses.append(value)

            form = Form()
            form.ShowInTaskbar = False
            form.CreateControl()
            _handle = form.Handle  # Create a hidden native root; never Show it.
            panel = Panel()
            panel.Dock = DockStyle.Fill
            form.Controls.Add(panel)
            _panel_handle = panel.Handle
            fixture_payload = not_ready_payload()
            fixture_payload["source_ready"] = True
            serialized = json.dumps(fixture_payload, separators=(",", ":"))
            # Deliberately no JavaScript timer: later messages can only be
            # generated by the helper's native five-second event dispatch.
            script = ("(() => {const p=" + serialized + ";const emit=()=>{p.observed_at=new Date().toISOString();"
                      "window.chrome.webview.postMessage(JSON.stringify(p));};window.addEventListener("
                      + json.dumps(NATIVE_TICK_EVENT)
                      + ",()=>{window.__offlineNativeTicks=(window.__offlineNativeTicks||0)+1;emit();});emit();})();")
            binding = create_source_control(panel, temporary_root / "profile", script, payload, status)
            deadline = time.monotonic() + 35

            def wait_for(condition) -> None:
                while not condition():
                    Application.DoEvents()
                    assert not form.Visible, "The offline test must remain invisible"
                    if time.monotonic() >= deadline:
                        raise TimeoutError("Offline WebView2 fixture timed out: " + str(statuses[-4:]))
                    time.sleep(0.01)

            wait_for(lambda: binding.core is not None and binding._initialized)
            browser_pid = int(binding.core.BrowserProcessId)
            binding.core.SetVirtualHostNameToFolderMapping(
                "tougu.zx093.cn", str(fixture_root), CoreWebView2HostResourceAccessKind.DenyCors
            )
            # Every application web resource must be served locally; a forgotten
            # fixture resource fails locally instead of falling back to a server.
            requested = []
            blocked_streams = []

            def requested_event(_sender, args):
                uri = str(args.Request.Uri)
                requested.append(uri)
                if not is_document_url(uri):
                    stream = MemoryStream(Array[Byte](list(b"offline fixture: external request blocked")))
                    blocked_streams.append(stream)
                    args.Response = binding.core.Environment.CreateWebResourceResponse(
                        stream, 403, "Offline fixture", "Content-Type: text/plain"
                    )

            binding.core.AddWebResourceRequestedFilter("*", CoreWebView2WebResourceContext.All)
            binding.core.WebResourceRequested += requested_event
            binding.navigate_to_source(LOGIN_URL)
            wait_for(lambda: binding._document_ready and str(binding.core.Source) == LOGIN_URL)
            assert not any(value["source_ready"] for value in payloads)
            binding.core.ExecuteScriptAsync("location.hash='/chatRoom?id=&teacherId=VzPD.Y8fIGs_'")
            wait_for(lambda: any(value["source_ready"] for value in payloads))
            assert binding._native_tick_timer.Interval == NATIVE_TICK_INTERVAL_MS == 5000
            first_count = sum(value["source_ready"] for value in payloads)
            wait_for(lambda: sum(value["source_ready"] for value in payloads) > first_count)
            first_tick_at = time.monotonic()
            next_count = sum(value["source_ready"] for value in payloads)
            wait_for(lambda: sum(value["source_ready"] for value in payloads) > next_count)
            assert time.monotonic() - first_tick_at >= 4.0
            native_ticks = binding.core.ExecuteScriptAsync("window.__offlineNativeTicks || 0")
            wait_for(lambda: native_ticks.IsCompleted)
            assert int(json.loads(str(native_ticks.Result))) >= 2
            assert not binding.core.Settings.AreHostObjectsAllowed
            for name in ("IsPasswordAutosaveEnabled", "IsGeneralAutofillEnabled"):
                if hasattr(binding.core.Settings, name):
                    assert getattr(binding.core.Settings, name) is False
            assert binding.control.CreationProperties.UserDataFolder == str(temporary_root / "profile")
            assert binding.control.CreationProperties.IsInPrivateModeEnabled is False
            persisted = binding.core.ExecuteScriptAsync("localStorage.setItem('offline-profile-smoke','kept'); 'stored'")
            wait_for(lambda: persisted.IsCompleted)
            assert json.loads(str(persisted.Result)) == "stored"
            marker = len(payloads)
            binding.core.ExecuteScriptAsync("location.hash='/?teacherId=VzPD.Y8fIGs_'")
            wait_for(lambda: len(payloads) > marker and not payloads[-1]["source_ready"])
            assert any(value["reason"] == "left_teacher_route" for value in statuses)
            binding.core.Navigate("https://example.invalid/blocked")
            wait_for(lambda: any(value["reason"] == "top_level_navigation_blocked" for value in statuses))
            assert is_document_url(str(binding.core.Source))
            marker = len(payloads)
            binding.core.ExecuteScriptAsync("location.hash='/chatRoom?id=&teacherId=VzPD.Y8fIGs_'")
            wait_for(lambda: any(value["source_ready"] for value in payloads[marker:]))
            binding.core.ExecuteScriptAsync("window.chrome.webview.postMessage('{bad json')")
            wait_for(lambda: any(value["reason"] == "invalid_source_message" for value in statuses))
            assert payloads[-1]["source_ready"] is False
            native_timer = binding._native_tick_timer
            binding.dispose()
            assert native_timer.Enabled is False
            binding = None
            try:
                Process.GetProcessById(browser_pid).WaitForExit(3000)
            except Exception:
                pass
            binding = create_source_control(panel, temporary_root / "profile", script, payload, status)
            wait_for(lambda: binding.core is not None and binding._initialized)
            browser_pid = int(binding.core.BrowserProcessId)
            binding.core.SetVirtualHostNameToFolderMapping(
                "tougu.zx093.cn", str(fixture_root), CoreWebView2HostResourceAccessKind.DenyCors
            )
            binding.navigate_to_source(LOGIN_URL)
            wait_for(lambda: binding._document_ready and str(binding.core.Source) == LOGIN_URL)
            restored = binding.core.ExecuteScriptAsync("localStorage.getItem('offline-profile-smoke')")
            wait_for(lambda: restored.IsCompleted)
            assert json.loads(str(restored.Result)) == "kept"
            output.put({"ok": True, "all_windows_invisible": True, "offline_local_fixture": True,
                        "hash_entry_injects": True, "hash_exit_marks_not_ready": True,
                        "webmessage_received_and_validated": True, "invalid_json_marks_not_ready": True,
                        "external_top_navigation_canceled": True,
                        "callbacks_on_ui_thread": True, "persistent_own_profile": True,
                        "local_storage_survives_control_recreation": True,
                        "hidden_native_five_second_ticks_verified": True,
                        "native_timer_stopped_on_dispose": True,
                        "no_host_objects_or_js_api": True, "password_save_disabled": True,
                        "real_login_requests": 0, "real_ths_mutations": 0})
        except BaseException as error:
            output.put(error)
        finally:
            if binding is not None:
                binding.dispose()
            if form is not None:
                form.Dispose()
            if browser_pid:
                try:
                    Process.GetProcessById(browser_pid).WaitForExit(3000)
                except Exception:
                    pass

    thread = Thread(ThreadStart(worker))
    thread.SetApartmentState(ApartmentState.STA)
    thread.Start()
    thread.Join(45000)
    if thread.IsAlive:
        raise TimeoutError("Offline source-control worker did not finish")
    result = output.get_nowait()
    # The recursive cleanup is restricted to the exact freshly created temp root.
    assert temporary_root.parent == Path(tempfile.gettempdir()).resolve()
    assert temporary_root.name.startswith("codex-teacher-webview-offline-")
    try:
        shutil.rmtree(temporary_root)
    except OSError:
        pass  # Runtime antivirus locks may temporarily retain this own test profile.
    if isinstance(result, BaseException):
        raise result
    return result


if __name__ == "__main__":
    print(json.dumps({"pure": pure_checks(), "native": native_smoke()}, ensure_ascii=False, separators=(",", ":")))
